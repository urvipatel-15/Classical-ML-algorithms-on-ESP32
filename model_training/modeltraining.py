nb = models['NaiveBayes']

theta = nb.theta_
var   = nb.var_ + 1e-9
priors = np.log(nb.class_prior_)

n_classes, n_features = theta.shape

theta_c = str(theta.tolist()).replace('[', '{').replace(']', '}')
var_c   = str(var.tolist()).replace('[', '{').replace(']', '}')
prior_c = str(priors.tolist()).replace('[', '{').replace(']', '}')

nb_code = f"""
// Gaussian Naive Bayes - Manual Implementation
#include <math.h>

#define N_CLASSES {n_classes}
#define N_FEATURES {n_features}

const float nb_theta[N_CLASSES][N_FEATURES] = {theta_c};
const float nb_var[N_CLASSES][N_FEATURES]   = {var_c};
const float nb_prior[N_CLASSES]             = {prior_c};

// Log Gaussian probability
float log_gaussian(float x, float mean, float var) {{
    return -0.5 * log(2 * 3.1415926 * var) - ((x - mean)*(x - mean)) / (2 * var);
}}

// Prediction function
int nb_predict(float input[N_FEATURES]) {{
    float best_score = -1e30;
    int best_class = 0;

    for (int c = 0; c < N_CLASSES; c++) {{
        float score = nb_prior[c];

        for (int f = 0; f < N_FEATURES; f++) {{
            score += log_gaussian(input[f], nb_theta[c][f], nb_var[c][f]);
        }}

        if (score > best_score) {{
            best_score = score;
            best_class = c;
        }}
    }}

    return best_class;
}}
"""

with open('models/model_nb.h', 'w') as f:
    f.write(nb_code)

print("Exported model_nb.h")


